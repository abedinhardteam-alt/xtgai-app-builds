package com.ishaq.xtgapps.shell;

import android.annotation.SuppressLint;
import android.app.Activity;
import android.graphics.Typeface;
import android.os.Bundle;
import android.os.Handler;
import android.os.Looper;
import android.util.TypedValue;
import android.view.Gravity;
import android.view.View;
import android.webkit.WebChromeClient;
import android.webkit.WebResourceRequest;
import android.webkit.WebResourceResponse;
import android.webkit.WebSettings;
import android.webkit.WebView;
import android.webkit.WebViewClient;
import android.widget.FrameLayout;
import android.widget.ImageView;
import android.widget.LinearLayout;
import android.widget.TextView;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Collections;

/** Native shell generated by XTG AI App Builder: branded splash + offline, sandboxed WebView running assets/index.html. */
public class MainActivity extends Activity {
    private static final String BASE = "https://app.xtgai.local/";
    private WebView web;

    @SuppressLint("SetJavaScriptEnabled")
    @Override protected void onCreate(Bundle state) {
        super.onCreate(state);
        FrameLayout root = new FrameLayout(this);
        web = new WebView(this);
        WebSettings s = web.getSettings();
        s.setJavaScriptEnabled(true);
        s.setDomStorageEnabled(true);          // localStorage keeps the app's data
        s.setDatabaseEnabled(true);
        s.setAllowFileAccess(false);
        s.setAllowContentAccess(false);
        s.setGeolocationEnabled(false);
        s.setSupportMultipleWindows(false);
        s.setMediaPlaybackRequiresUserGesture(false);
        web.setWebChromeClient(new WebChromeClient());   // alert()/confirm()/prompt() dialogs
        web.setWebViewClient(new WebViewClient() {
            @Override public boolean shouldOverrideUrlLoading(WebView v, WebResourceRequest r) {
                String u = r.getUrl().toString();
                return !u.startsWith(BASE);    // stay inside the app
            }
            @Override public WebResourceResponse shouldInterceptRequest(WebView v, WebResourceRequest r) {
                String u = r.getUrl().toString();
                if (u.startsWith("data:") || u.startsWith("blob:") || u.startsWith(BASE)) return null;
                return new WebResourceResponse("text/plain", "utf-8", 403, "Offline app", Collections.emptyMap(),
                        new ByteArrayInputStream(new byte[0]));
            }
        });
        root.addView(web, new FrameLayout.LayoutParams(-1, -1));
        final View splash = buildSplash();
        root.addView(splash, new FrameLayout.LayoutParams(-1, -1));
        setContentView(root);
        if (state != null) web.restoreState(state);
        else web.loadDataWithBaseURL(BASE, readAsset("index.html"), "text/html", "utf-8", null);
        new Handler(Looper.getMainLooper()).postDelayed(() ->
                splash.animate().alpha(0f).setDuration(350).withEndAction(() -> splash.setVisibility(View.GONE)).start(), 1300);
    }

    private View buildSplash() {
        LinearLayout l = new LinearLayout(this);
        l.setOrientation(LinearLayout.VERTICAL);
        l.setGravity(Gravity.CENTER);
        l.setBackgroundResource(R.drawable.ic_bg);
        l.setClickable(true);
        ImageView icon = new ImageView(this);
        icon.setImageResource(R.drawable.ic_fg);
        int sz = dp(150);
        l.addView(icon, new LinearLayout.LayoutParams(sz, sz));
        TextView name = new TextView(this);
        name.setText(R.string.app_name);
        name.setTextColor(0xFFFFFFFF);
        name.setTextSize(TypedValue.COMPLEX_UNIT_SP, 26);
        name.setTypeface(Typeface.DEFAULT_BOLD);
        name.setGravity(Gravity.CENTER);
        name.setPadding(dp(24), 0, dp(24), dp(8));
        l.addView(name);
        TextView credit = new TextView(this);
        credit.setText(R.string.credit);
        credit.setTextColor(0xCCFFFFFF);
        credit.setTextSize(TypedValue.COMPLEX_UNIT_SP, 13);
        credit.setGravity(Gravity.CENTER);
        l.addView(credit);
        return l;
    }

    private int dp(int v) { return Math.round(v * getResources().getDisplayMetrics().density); }

    private String readAsset(String n) {
        try (InputStream in = getAssets().open(n)) {
            ByteArrayOutputStream o = new ByteArrayOutputStream();
            byte[] b = new byte[16384]; int r;
            while ((r = in.read(b)) > 0) o.write(b, 0, r);
            return new String(o.toByteArray(), StandardCharsets.UTF_8);
        } catch (Exception e) { return "<html><body><h3>App file missing</h3></body></html>"; }
    }

    @Override protected void onSaveInstanceState(Bundle out) { super.onSaveInstanceState(out); web.saveState(out); }
    @SuppressWarnings("deprecation") @Override public void onBackPressed() { if (web.canGoBack()) web.goBack(); else super.onBackPressed(); }
    @Override protected void onDestroy() { if (web != null) web.destroy(); super.onDestroy(); }
}
